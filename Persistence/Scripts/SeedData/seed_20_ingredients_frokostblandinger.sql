SELECT pg_temp.seed_uuid_v7(), i.id, v.nutrient_id, v.quantity, v.value_source_id
FROM seed_value v JOIN ingredient i ON i.source_id = v.source_id
ON CONFLICT DO NOTHING;

INSERT INTO ingredient_portion (id, ingredient_id, unit_id, grams_per_portion)
SELECT pg_temp.seed_uuid_v7(), i.id, p.unit_id, p.grams
FROM seed_portion p JOIN ingredient i ON i.source_id = p.source_id
WHERE NOT EXISTS (SELECT 1 FROM ingredient_portion x
                  WHERE x.ingredient_id = i.id AND x.unit_id = p.unit_id AND x.grams_per_portion = p.grams);

