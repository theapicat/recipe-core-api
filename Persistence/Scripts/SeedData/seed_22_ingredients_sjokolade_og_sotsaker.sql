-- Alle får is_verified = false: kilden har ingen allergendata, så allergener er ikke tilordnet ennå. Admin kan
-- rydde bort det som ikke trengs og verifisere resten. Navn er små bokstaver. Næringsverdier er kun de som er målt
-- (sparsomt); 0 betyr målt som null, manglende verdi betyr ukjent. Kobles på source_id (Matvaretabellens matvare-id).
-- Idempotent: eksisterende rader (samme source_id / verdi / kobling) hoppes over.

-- Midlertidig funksjon (finnes kun i denne økten): UUIDv7 lik Guid.CreateVersion7() i applikasjonen, som Postgres 16
-- ikke har innebygd. Gir tidssorterbare id-er, slik som resten av databasen.
CREATE OR REPLACE FUNCTION pg_temp.seed_uuid_v7() RETURNS uuid
LANGUAGE sql VOLATILE AS $$
    SELECT encode(
        set_bit(set_bit(
            overlay(uuid_send(gen_random_uuid())
                    PLACING substring(int8send((extract(epoch FROM clock_timestamp()) * 1000)::bigint) FROM 3) FROM 1 FOR 6),
            52, 1), 53, 1),
        'hex')::uuid;
$$;

